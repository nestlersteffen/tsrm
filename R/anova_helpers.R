
#- --- function that computes the means of a variable in the levels of idvar

anova_means <- function( variable=NULL, idvar=NULL ) 
{
	sums <- rowsum( variable, idvar )
	ns   <- tabulate( match( idvar, unique( idvar ) ) )
	return( as.numeric( sums / ns) )
}

